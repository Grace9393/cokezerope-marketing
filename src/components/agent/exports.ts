import type { Brief, EvidenceRow, Proposal } from "@/lib/agent/types";
import type { ActivityEntry } from "./useApprovals";

// Client-side executors for approved proposals. Nothing is ever sent:
// files are downloaded locally and emails open as a mailto: draft.

export function downloadText(filename: string, text: string, mime = "text/markdown;charset=utf-8") {
  const blob = new Blob([text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

const fmt = (v: number | null) =>
  v == null ? "—" : new Intl.NumberFormat("en-US", { maximumFractionDigits: 0 }).format(v);

export function briefToMarkdown(
  question: string,
  brief: Brief,
  evidence: EvidenceRow[],
  proposal?: Proposal,
): string {
  const cited = new Set(
    brief.findings.flatMap((f) => f.evidenceIds).concat(proposal?.evidenceIds ?? []),
  );
  const rows = evidence.filter((e) => cited.has(e.id));
  const lines = [
    `# ${proposal?.title || brief.headline}`,
    "",
    `_Generated by Ace (Gemini) · ${new Date().toLocaleString()}_`,
    "",
    `**Question:** ${question}`,
    "",
    `## Headline`,
    brief.headline,
    "",
    `## Findings`,
    ...brief.findings.map(
      (f, i) =>
        `${i + 1}. ${f.text}${f.evidenceIds.length ? ` _(evidence: ${f.evidenceIds.join("; ")})_` : ""}`,
    ),
    "",
  ];
  if (brief.actions.length) {
    lines.push(
      "## Proposed actions",
      ...brief.actions.map((a) => `- **${a.title}** — ${a.details}`),
      "",
    );
  }
  if (proposal?.details) lines.push("## Notes", proposal.details, "");
  lines.push(
    "## Evidence",
    "",
    "| Row id | Category | Product | Metric | Year | Total |",
    "|---|---|---|---|---|---|",
  );
  for (const r of rows)
    lines.push(
      `| ${r.id} | ${r.category} | ${r.product} | ${r.metric} | ${r.year} | ${fmt(r.total)} |`,
    );
  if (!rows.length) lines.push("| — | | | | | |");
  lines.push(
    "",
    "_Source: uploaded make-up sales dashboard. Numbers come from tool calls, not model memory._",
  );
  return lines.join("\n");
}

export function openMailDraft(subject: string, body: string) {
  const href = `mailto:?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  window.location.href = href;
}

export function activityToMarkdown(entries: ActivityEntry[]): string {
  const lines = [
    "# Ace activity log",
    "",
    "| Time | Decision | Action | Title | Question |",
    "|---|---|---|---|---|",
    ...entries.map(
      (e) =>
        `| ${new Date(e.ts).toLocaleString()} | ${e.decision} | ${e.type} | ${e.title.replace(/\|/g, "/")} | ${(e.question ?? "").replace(/\|/g, "/")} |`,
    ),
  ];
  return lines.join("\n");
}
