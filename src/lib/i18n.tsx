const DICTS: Record<Lang, Dict> = { zh, en };

const MONTHS_LOCAL: Record<Lang, string[]> = {
  zh: ["1月", "2月", "3月", "4月", "5月", "6月", "7月", "8月", "9月", "10月", "11月", "12月"],
  en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
};

type I18nValue = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  months: string[];
  monthAt: (i: number) => string;
  metricLabel: (m: Metric) => string;
  metricShort: (m: Metric) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

function interpolate(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function I18nProvider({ children, forceLang }: { children: ReactNode; forceLang?: Lang }) {
  const [lang, setLangState] = useState<Lang>(forceLang ?? "zh");

  useEffect(() => {
    if (forceLang) return;
    const stored = typeof window !== "undefined" ? window.localStorage.getItem(STORAGE_KEY) : null;
    if (stored === "en" || stored === "zh") setLangState(stored);
  }, [forceLang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") window.localStorage.setItem(STORAGE_KEY, l);
  };

  const t = (key: string, vars?: Record<string, string | number>) =>
    interpolate(DICTS[lang][key] ?? DICTS.en[key] ?? key, vars);

  const value: I18nValue = {
    lang,
    setLang,
    t,
    months: MONTHS_LOCAL[lang],
    monthAt: (i) => MONTHS_LOCAL[lang][i] ?? "",
    metricLabel: (m) => t(`metricLabel.${m}`),
    metricShort: (m) => t(`metric.${m}`),
  };

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
